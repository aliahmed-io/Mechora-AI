"""Exercise the complete browser workflow against running Next.js and FastAPI."""
from pathlib import Path
import json
from playwright.sync_api import sync_playwright, expect
ROOT=Path(__file__).resolve().parents[1]
OUT=ROOT/'output'/'qa';OUT.mkdir(parents=True,exist_ok=True)
with sync_playwright() as p:
    browser=p.chromium.launch(headless=True,channel='chrome')
    page=browser.new_page(viewport={'width':1440,'height':1000},accept_downloads=True)
    errors=[];page.on('pageerror',lambda e:errors.append(str(e)))
    page.goto('http://127.0.0.1:3000');page.wait_for_load_state('networkidle')
    page.get_by_role('button',name='See how it works',exact=True).click()
    expect(page.get_by_role('dialog')).to_be_visible()
    page.keyboard.press('Escape')
    expect(page.get_by_role('dialog')).not_to_be_visible()
    page.get_by_role('link',name='Analyze equipment',exact=True).click();page.wait_for_load_state('networkidle')
    expect(page.get_by_role('heading',name='The data import studio')).to_be_visible()
    page.get_by_role('button',name='Use sample dataset').click()
    expect(page.get_by_text('Schema verified')).to_be_visible(timeout=30000)
    page.screenshot(path=str(OUT/'import-desktop.png'),full_page=True)
    page.get_by_role('button',name='Run analysis',exact=True).click()
    page.wait_for_url('**/dashboard?analysis=*',timeout=60000)
    expect(page.get_by_text('Analyzed observations',exact=True)).to_be_visible(timeout=30000)
    expect(page.locator('.stat-card').first).to_contain_text('2,000')
    page.wait_for_load_state('networkidle');page.screenshot(path=str(OUT/'dashboard-desktop.png'),full_page=True)
    url=page.url;analysis_id=url.split('analysis=')[1]
    page.get_by_role('link',name='Equipment records',exact=True).click()
    expect(page.locator('tbody tr')).to_have_count(12,timeout=30000)
    page.locator('.records-toolbar select').nth(0).select_option('High')
    expect(page.locator('tbody tr').first.locator('.risk-badge')).to_have_text('High',timeout=30000)
    page.get_by_role('link',name='Inspect OBS-',exact=False).first.click()
    expect(page.get_by_text('What changes the estimate?')).to_be_visible(timeout=60000)
    expect(page.locator('.sensitivity-list>div')).to_have_count(5)
    page.screenshot(path=str(OUT/'diagnostics-desktop.png'),full_page=True)
    page.get_by_role('button',name='Single observation',exact=True).click()
    page.get_by_role('button',name='Estimate failure risk',exact=True).click()
    expect(page.get_by_text('What changes the estimate?')).to_be_visible(timeout=30000)
    page.get_by_role('button',name='Saved observation',exact=False).click()
    expect(page.locator('.detail-machine')).to_be_visible()
    expect(page.locator('.diagnosis-dial')).to_contain_text('99.5')
    page.get_by_role('link',name='Model laboratory',exact=True).click()
    expect(page.get_by_text('Confusion matrix',exact=True)).to_be_visible(timeout=30000)
    expect(page.get_by_text('True positives',exact=True)).to_be_visible()
    page.screenshot(path=str(OUT/'models-desktop.png'),full_page=True)
    page.get_by_role('link',name='Risk analysis',exact=True).click()
    expect(page.get_by_text('A considered threshold',exact=True)).to_be_visible(timeout=30000)
    page.locator('input[type=range]').nth(0).fill('0.1')
    page.locator('input[type=range]').nth(1).fill('0.5')
    page.get_by_role('button',name='Apply & save analysis').click()
    page.wait_for_url(lambda u:'/dashboard?analysis=' in u and analysis_id not in u,timeout=60000)
    expect(page.get_by_text('Analyzed observations',exact=True)).to_be_visible(timeout=30000)
    page.reload();expect(page.locator('.stat-card').first).to_contain_text('2,000',timeout=30000)
    page.get_by_role('link',name='Reports',exact=True).click()
    page.get_by_role('button',name='Generate PDF report').click()
    ready=page.get_by_role('link',name='Report ready. Download PDF')
    expect(ready).to_be_visible(timeout=30000)
    with page.expect_download() as dl:ready.click()
    dl.value.save_as(OUT/'analysis-report.pdf')
    assert (OUT/'analysis-report.pdf').read_bytes().startswith(b'%PDF')
    with page.expect_download() as dl:page.get_by_role('link',name='Download results CSV').click()
    dl.value.save_as(OUT/'predictions.csv')
    assert len((OUT/'predictions.csv').read_text().splitlines())==2001
    # Invalid upload is recoverable.
    page.get_by_role('link',name='Data import',exact=True).click()
    page.locator('input[type=file]').set_input_files({'name':'invalid.csv','mimeType':'text/csv','buffer':b'wrong\n1'})
    expect(page.locator('.validation-error')).to_contain_text('Missing required columns',timeout=30000)
    # Search, sorting and pagination.
    page.goto(f'http://127.0.0.1:3000/records?analysis={analysis_id}')
    expect(page.locator('tbody tr')).to_have_count(12,timeout=30000)
    page.get_by_role('button',name='Next page').click();expect(page.locator('.pagination')).to_contain_text('Page 2')
    page.get_by_role('textbox',name='Search observations').fill('OBS-00001')
    expect(page.locator('tbody tr')).to_have_count(1,timeout=30000)
    # Mobile functional navigation and no page overflow.
    page.set_viewport_size({'width':390,'height':844})
    for path in ['/',f'/dashboard?analysis={analysis_id}','/import',f'/diagnostics?analysis={analysis_id}','/models','/reports']:
        page.goto('http://127.0.0.1:3000'+path);page.wait_for_load_state('networkidle')
        assert not page.evaluate('document.documentElement.scrollWidth > innerWidth'),path
        page.screenshot(path=str(OUT/(('landing' if path=='/' else path.split('?')[0].strip('/'))+'-mobile.png')),full_page=True)
    page.get_by_role('button',name='Open navigation').click()
    expect(page.get_by_role('link',name='Data import',exact=True)).to_be_visible()
    assert not errors,errors
    print(json.dumps({'status':'passed','analysis':analysis_id,'javascript_errors':errors,'checks':['landing interactions','keyboard dialog dismissal','sample import','real inference','record filter','diagnostic explanation','single-observation inference','model evaluation','threshold save','refresh persistence','PDF download','CSV export','invalid upload','search','pagination','six mobile routes','mobile navigation']}))
    browser.close()
